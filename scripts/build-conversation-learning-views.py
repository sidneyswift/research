#!/usr/bin/env python3
"""Render review annotations into deterministic views; never create training pairs.

The reviewed per-chat ledger remains authoritative. Candidate text is copied, not
reinterpreted. Chat-level candidates without local locators remain explicitly
chat-scoped; this script cannot invent a pre-correction context or desired answer.
"""
import argparse
import json
from pathlib import Path


INTERVENTIONS = ('interventions', 'observed_interventions', 'observed_agent_corrections')
LESSONS = ('lesson_candidates', 'holistic_lesson_candidates')


def rows(path):
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def local_ids(value, known):
    found = []
    locator_fields={'evidence_ids','evidence_item_ids','feedback_item_id','repair_item_id','item_id'}
    def walk(v, field=None):
        if field in locator_fields and isinstance(v,str) and v not in known:
            raise ValueError('Unknown annotation locator: '+v)
        if isinstance(v, str) and v in known and v not in found:
            found.append(v)
        elif isinstance(v, dict):
            for key,item in v.items():
                walk(item,key)
        elif isinstance(v, list):
            for item in v:
                walk(item,field)
    walk(value)
    return found


def build(run):
    reviews = sorted(rows(run / 'reviews.jsonl'), key=lambda r: r['alias'])
    output = {'interventions': [], 'lessons': []}
    for review in reviews:
        alias = review['alias']
        known = set(review['reviewed_message_ids'])
        for kind, fields in [('interventions', INTERVENTIONS), ('lessons', LESSONS)]:
            number = 0
            for field in fields:
                values = review.get(field, [])
                if not isinstance(values, (list, dict, str)):
                    continue  # Some triage reviews store a count, not annotations.
                if not isinstance(values, list):
                    values = [values]
                for index, value in enumerate(values):
                    number += 1
                    ids = local_ids(value, known)
                    record = dict(
                        schema_version=1, id=f'{alias}-{kind}-{number:03}',
                        record_type='intervention-candidate' if kind == 'interventions' else 'lesson-candidate',
                        alias=alias, source_ref=review['source_ref'],
                        annotation_ref={'review_id': review['id'], 'field': field, 'index': index},
                        evidence_scope='message-linked' if ids else 'chat-level',
                        evidence_refs=[{'alias': alias, 'item_id': item} for item in ids],
                        annotation=value, interpretation_limits=review['interpretation_limits'],
                        origin='model-review', human_review_status='unreviewed',
                        training_eligible=False, dataset_split='development',
                        allowed_uses=['private_analysis'], measured_improvement=None,
                        context_cutoff=None, desired_target=None,
                    )
                    for restriction in ('source_reuse_restricted', 'excluded_from_training_and_publication'):
                        if restriction in review:
                            record[restriction] = review[restriction]
                    output[kind].append(record)
    for kind, records in output.items():
        (run / (kind + '.jsonl')).write_text(''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in records))
    # A searchable human surface, rendered from the same ledger rather than a
    # second manually maintained version of each chat's findings.
    lines = ['# Per-chat review catalog', '',
             'Generated by `scripts/build-conversation-learning-views.py`; edit the review ledger, not this surface.', '',
             'Model-reviewed candidates, not human-approved training labels. Historical agent reports are not fresh verification.', '']
    for review in reviews:
        alias = review['alias']
        lines += [f'## {alias}', '', f"[[{review['source_ref']}]]", '',
                  review['episode_observation'], '']
        for field in LESSONS:
            values = review.get(field, [])
            if not isinstance(values, (list, dict, str)):
                continue
            if not isinstance(values, list):
                values = [values]
            for value in values:
                if isinstance(value, str):
                    text = value
                else:
                    text = value.get('lesson', value.get('mechanism', json.dumps(value, ensure_ascii=False)))
                lines += [f'- Candidate: {text}']
        limits = review['interpretation_limits']
        lines += ['', 'Limits: ' + (' '.join(limits) if isinstance(limits, list) else limits), '']
    (run / 'review-catalog.md').write_text('\n'.join(lines))
    return {kind: len(records) for kind, records in output.items()}


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--run', type=Path, required=True)
    print(json.dumps(build(p.parse_args().run)))
